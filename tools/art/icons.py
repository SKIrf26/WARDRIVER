"""Anti-aliased UI icon masks for SKIrf (Material Design Icons, Apache-2.0 /
Pictogrammers free licence).  Each icon is stored as a 4-bit alpha mask
(16 coverage levels) so the firmware can tint it with any theme colour and
blend it onto any background without jaggies."""
import os, sys
from PIL import Image, ImageDraw, ImageFont

# The Material Design Icons webfont (v6.9.96), e.g. from the @mdi/font npm package.
TTF = os.environ.get("MDI_TTF", "materialdesignicons-webfont.ttf")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")

ICONS = {
    # name           glyph
    "radar":       0xF0437,
    "satellite":   0xF0471,
    "cog":         0xF0493,
    "brightness":  0xF00DF,
    "palette":     0xF03D8,
    "rotate":      0xF0475,
    "portal":      0xF0003,
    "folder":      0xF024B,
    "wifi":        0xF05A9,
    "alert":       0xF0026,
    "chip":        0xF061A,
    "tap":         0xF0741,
    "trophy":      0xF0538,
    "shield":      0xF113B,
    "bluetooth":   0xF00AF,
    "gps":         0xF01A4,
    "sd":          0xF0479,
    "play":        0xF040A,
    "stop":        0xF04DB,
    "home":        0xF02DC,
    "back":        0xF004D,
    "up":          0xF0143,
    "down":        0xF0140,
    "car":         0xF07AB,
    "moto":        0xF037C,
    "bike":        0xF00A3,
    "upload":      0xF0552,
    "trash":       0xF01B4,
    "check":       0xF012C,
    "refresh":     0xF0450,
    "speed":       0xF04C5,
    "nav":         0xF0390,
    "pin":         0xF034E,
}

SIZES = (14, 20, 26)


def render(code, n, fill=0.86):
    big = n * 8
    font = ImageFont.truetype(TTF, big)
    canvas = Image.new("L", (big * 2, big * 2), 0)
    ImageDraw.Draw(canvas).text((big, big), chr(code), font=font, fill=255, anchor="mm")
    bb = canvas.getbbox()
    crop = canvas.crop(bb)
    target = int(round(n * 8 * fill))
    s = target / max(crop.size)
    crop = crop.resize((max(1, int(crop.width * s)), max(1, int(crop.height * s))), Image.LANCZOS)
    sq = Image.new("L", (n * 8, n * 8), 0)
    sq.paste(crop, ((n * 8 - crop.width) // 2, (n * 8 - crop.height) // 2))
    small = sq.resize((n, n), Image.BOX)
    return [[min(15, (small.getpixel((x, y)) + 8) // 17) for x in range(n)] for y in range(n)]


def main(hdr):
    masks = {}
    for n in SIZES:
        for name, code in ICONS.items():
            masks[(name, n)] = render(code, n)
    # preview sheet
    cell = 34
    sheet = Image.new("RGB", (len(ICONS) * cell + 8, len(SIZES) * cell + 8), (20, 20, 24))
    for j, n in enumerate(SIZES):
        for i, name in enumerate(ICONS):
            m = masks[(name, n)]
            for y in range(n):
                for x in range(n):
                    a = m[y][x] / 15
                    sheet.putpixel((4 + i * cell + x, 4 + j * cell + y),
                                   (int(20 + a * 215), int(20 + a * 215), int(24 + a * 220)))
    sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST).save(os.path.join(OUT, "icons.png"))

    L = ["#pragma once",
         "// Auto-generated by art/icons.py - Material Design Icons (Apache 2.0).",
         "// 4-bit alpha masks, 2 px per byte (high nibble = left pixel).",
         "#include <stdint.h>",
         "struct SkiIcon { uint8_t n; const uint8_t* a; };"]
    names = list(ICONS)
    for n in SIZES:
        for name in names:
            m = masks[(name, n)]
            data = []
            for row in m:
                for x in range(0, n, 2):
                    data.append((row[x] << 4) | (row[x + 1] if x + 1 < n else 0))
            L.append(f"static const uint8_t ICO_{name.upper()}_{n}_D[{len(data)}] = {{" +
                     ",".join("0x%02X" % v for v in data) + "};")
    L.append("enum SkiIconId {")
    L.append("  " + ", ".join(f"ICON_{nm.upper()}" for nm in names) + ", ICON_COUNT")
    L.append("};")
    for n in SIZES:
        L.append(f"static const SkiIcon ICONS_{n}[ICON_COUNT] = {{")
        L.append("  " + ", ".join(f"{{{n}, ICO_{nm.upper()}_{n}_D}}" for nm in names))
        L.append("};")
    with open(hdr, "w") as f:
        f.write("\n".join(L) + "\n")
    print("icons", len(names), "x", SIZES)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(OUT, "SKIrf_Icons.h"))
