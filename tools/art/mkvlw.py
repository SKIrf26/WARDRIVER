"""Generate LovyanGFX/TFT_eSPI VLW smooth fonts as a C header.
caps=True: lowercase letters render as capitals, glyphs are clipped to a tight
cap box so MC_DATUM centring is optical, and tracking (letter spacing) is added."""
import struct, sys
from PIL import Image, ImageDraw, ImageFont

def make(ttf, px, caps, track):
    f = ImageFont.truetype(ttf, px)
    capH = -f.getbbox('H', anchor='ls')[1]
    top_lim = int(round(capH * 1.10)) if caps else 10**6
    bot_lim = int(round(capH * 0.16)) if caps else 10**6
    glyphs = []
    for cp in range(32, 127):
        ch = chr(cp)
        src = ch.upper() if caps else ch
        adv = int(round(f.getlength(src) + track))
        if ch == ' ':
            glyphs.append((cp, 0, 0, max(2, int(round(px * 0.26 + track))), 0, 0, b'')); continue
        x0, y0, x1, y1 = f.getbbox(src, anchor='ls')
        lift = 0
        if caps and ch == '_':            # keep the underscore visible inside the caps box
            lift = y1 - bot_lim
        y0 -= lift; y1 -= lift
        y0 = max(y0, -top_lim); y1 = min(y1, bot_lim)
        w, h = x1 - x0, y1 - y0
        if w <= 0 or h <= 0:
            glyphs.append((cp, 0, 0, adv, 0, 0, b'')); continue
        im = Image.new('L', (w, h), 0)
        ImageDraw.Draw(im).text((-x0, -y0 - lift), src, font=f, fill=255, anchor='ls')
        glyphs.append((cp, h, w, adv, -y0, x0, im.tobytes()))
    asc = capH if caps else f.getmetrics()[0]
    desc = bot_lim if caps else f.getmetrics()[1]
    out = struct.pack('>6i', len(glyphs), 11, px, 0, asc, desc)
    for g in glyphs:
        out += struct.pack('>7i', g[0], g[1], g[2], g[3], g[4], g[5], 0)
    for g in glyphs: out += g[6]
    return out

specs = [l.split() for l in sys.argv[2:]]
hdr = ['#pragma once', '// Auto-generated by mkvlw.py from Saira Semi Condensed (SIL OFL 1.1).',
       '// Smooth (anti-aliased) VLW fonts. *_CAPS fonts render every letter as a capital.', '#include <stdint.h>']
for name, ttf, px, caps, track in specs:
    data = make(ttf, int(px), caps == '1', float(track))
    hdr.append('static const uint8_t %s[%d] = {' % (name, len(data)))
    for i in range(0, len(data), 24):
        hdr.append('  ' + ','.join('0x%02X' % b for b in data[i:i+24]) + ',')
    hdr.append('};')
open(sys.argv[1], 'w').write('\n'.join(hdr) + '\n')
print('wrote', sys.argv[1])
