"""Pack the web portal (tools/web/portal.html), its fonts and its logo into
src/SKIrf_WARDRIVER_C5_CYD/SKIrf_Web.h as gzip/PROGMEM byte arrays.

Needs: Pillow, fontTools, brotli.  Font sources: Saira Semi Condensed Medium + Bold
(SIL OFL 1.1), path in SAIRA_DIR (default /home/claude/fonts).
Run from the repo root:  python3 tools/web/make_web_assets.py
"""
import gzip, io, os, re, sys
from PIL import Image
from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'src', 'SKIrf_WARDRIVER_C5_CYD', 'SKIrf_Web.h')
FONTS = os.environ.get('SAIRA_DIR', '/home/claude/fonts')
UNI = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x203A]

def gz(b): return gzip.compress(b, 9, mtime=0)

def minify_html(s):
    s = re.sub(r'\n\s+', '\n', s)
    return s.strip().encode('utf-8')

def woff2(path):
    f = TTFont(path)
    o = subset.Options(); o.flavor = 'woff2'; o.layout_features = ['kern', 'liga', 'tnum']; o.name_IDs = [0, 1, 2]
    s = subset.Subsetter(o); s.populate(unicodes=UNI); s.subset(f)
    b = io.BytesIO(); f.flavor = 'woff2'; f.save(b); return b.getvalue()

def png(path, w):
    im = Image.open(path).convert('RGBA')
    h = round(im.height * w / im.width)
    im = im.resize((w, h), Image.LANCZOS).quantize(colors=64, method=Image.FASTOCTREE, dither=Image.NONE)
    b = io.BytesIO(); im.save(b, 'PNG', optimize=True); return b.getvalue()

assets = [
    ('WEB_INDEX_GZ', gz(minify_html(open(os.path.join(HERE, 'portal.html'), encoding='utf-8').read()))),
    ('WEB_FONT_M', woff2(os.path.join(FONTS, 'SairaSemiCondensed-Medium.ttf'))),
    ('WEB_FONT_B', woff2(os.path.join(FONTS, 'SairaSemiCondensed-Bold.ttf'))),
    ('WEB_LOGO', png(os.path.join(HERE, 'logo-mark.png'), 92)),
    ('WEB_FAVICON', png(os.path.join(HERE, 'logo-mark.png'), 48)),
]
with open(OUT, 'w') as o:
    o.write('#pragma once\n// Copyright (C) 2026 SKIrf Labs. Part of SKIrf Wardriver, free software under the GNU GPL v3 or later (see ../../LICENSE).\n')
    o.write('// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by tools/web/make_web_assets.py from tools/web/. Do not edit by hand.\n')
    o.write('// The fonts are subsets of Saira Semi Condensed (SIL OFL 1.1; see ../../licenses).\n#include <pgmspace.h>\n')
    for name, data in assets:
        o.write(f'\nconst size_t {name}_LEN = {len(data)};\nconst uint8_t {name}[] PROGMEM = {{\n')
        for i in range(0, len(data), 24):
            o.write('  ' + ','.join(str(x) for x in data[i:i + 24]) + ',\n')
        o.write('};\n')
        print(f'{name:14s} {len(data):7d} bytes')
